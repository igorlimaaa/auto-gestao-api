-- Cobranças que o Banco Inter emitiu mas que a importação não conseguiu ligar a uma unidade (ou que
-- a regra de negócio não deixa criar). O banco é a única origem das cobranças; sem este registro, uma
-- cobrança sem unidade correspondente sumiria em silêncio e o morador ficaria sem cobrança na tela.
-- É um retrato da última importação: a cada rodada o conjunto do condomínio é recalculado.
CREATE TABLE tb_cobranca_banco_pendente (
    id_cobranca_banco_pendente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_condominio              BIGINT NOT NULL REFERENCES tb_condominio (id_condominio),
    ds_codigo_solicitacao      VARCHAR(40) NOT NULL,
    ds_seu_numero              VARCHAR(30),
    dt_vencimento              DATE,
    vl_cobranca                DOUBLE PRECISION,
    ds_motivo                  VARCHAR(30) NOT NULL,
    dt_deteccao                TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_pendente_condominio_codigo UNIQUE (id_condominio, ds_codigo_solicitacao)
);
