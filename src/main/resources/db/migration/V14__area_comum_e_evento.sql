-- Agenda do condomínio: o catálogo de áreas comuns (cadastrado pelo síndico) e os eventos, que
-- podem ser reunião, reserva de área, evento social ou manutenção. Evento de morador nasce
-- PENDENTE e só passa a valer para os demais quando aprovado.

CREATE TABLE tb_area_comum (
    id_area_comum  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_condominio  BIGINT NOT NULL REFERENCES tb_condominio (id_condominio),
    ds_nome        VARCHAR(60) NOT NULL,
    ds_descricao   VARCHAR(300),
    in_reservavel  BOOLEAN NOT NULL DEFAULT FALSE,
    nr_capacidade  INTEGER,
    hr_abertura    TIME,
    hr_fechamento  TIME,
    in_ativa       BOOLEAN NOT NULL DEFAULT TRUE,
    dt_cadastro    TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT uk_area_comum_nome UNIQUE (id_condominio, ds_nome)
);

CREATE TABLE tb_evento (
    id_evento             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_condominio         BIGINT NOT NULL REFERENCES tb_condominio (id_condominio),
    id_area_comum         BIGINT REFERENCES tb_area_comum (id_area_comum),
    tp_evento             VARCHAR(20) NOT NULL,
    ds_titulo             VARCHAR(100) NOT NULL,
    ds_descricao          VARCHAR(500),
    dt_inicio             TIMESTAMP NOT NULL,
    dt_fim                TIMESTAMP NOT NULL,
    in_dia_inteiro        BOOLEAN NOT NULL DEFAULT FALSE,
    st_evento             VARCHAR(20) NOT NULL,
    id_unidade            BIGINT REFERENCES tb_unidade (id_unidade),
    ds_solicitante_email  VARCHAR(200),
    ds_solicitante_nome   VARCHAR(200),
    ds_motivo_decisao     VARCHAR(300),
    dt_decisao            TIMESTAMP,
    ds_decidido_por       VARCHAR(200),
    dt_cadastro           TIMESTAMP NOT NULL DEFAULT now()
);

CREATE INDEX ix_evento_condominio_periodo ON tb_evento (id_condominio, dt_inicio, dt_fim);
CREATE INDEX ix_evento_area_periodo ON tb_evento (id_area_comum, dt_inicio, dt_fim);
